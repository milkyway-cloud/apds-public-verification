import {chromium, expect} from '@playwright/test';
import fs from 'node:fs/promises';
const browser = await chromium.launch({channel:'chrome',headless:true});
const results=[];
for (const [version,port] of [['0.1.3',6214],['0.2.0',6215],['0.2.1',6216]]) {
 await fs.mkdir(`artifacts/${version}`,{recursive:true});
 const page=await browser.newPage({viewport:{width:1280,height:960}});
 const errors=[]; page.on('pageerror',e=>errors.push(e.message));
 const record={version,checks:[],pageErrors:errors};
 try {
  await page.goto(`http://127.0.0.1:${port}`);
  const save=page.getByRole('button',{name:'저장하기',exact:true});
  await save.click();
  await expect(save).toHaveAttribute('aria-busy','true');
  await save.evaluate(el=>{el.click();el.click();});
  await expect(page.getByTestId('save-button')).toHaveAttribute('data-attempts','1');
  await expect(page.getByTestId('save-status')).toContainText('저장하지 못했습니다');
  await save.click();
  await expect(page.getByTestId('save-status')).toHaveText('저장 완료');
  await expect(page.getByTestId('save-button')).toHaveAttribute('data-attempts','2');
  record.checks.push('save failure/retry, loading aria-busy and duplicate click blocked');
  const search=page.getByRole('textbox',{name:'팀 검색'});
  await search.fill('디자인');
  await expect(page.getByRole('table',{name:'팀 목록'})).toContainText('디자인');
  await expect(page.getByRole('table',{name:'팀 목록'})).not.toContainText('개발');
  await search.fill('없는팀');
  await expect(page.getByRole('table',{name:'팀 목록'})).not.toContainText('디자인');
  record.emptySearchText=await page.getByRole('region',{name:'팀 검색 목록'}).innerText();
  await search.fill('');
  record.checks.push('team-name search, unmatched result, reset');
  const table=page.getByRole('table',{name:'데이터셋별 질문 수와 완료 수'});
  await expect(table.getByRole('columnheader')).toHaveCount(3);
  await expect(table).toContainText('120'); await expect(table).toContainText('90');
  record.checks.push('read-only dataset count table, native headers and exact values');
  const trigger=page.getByRole('button',{name:'공유 권한 변경'});
  await trigger.click();
  const dialog=page.getByRole('dialog');
  await dialog.getByRole('radio',{name:'특정 그룹에게만 공개'}).click();
  await dialog.getByRole('button',{name:'확인',exact:true}).click();
  await expect(dialog).toContainText('공유할 그룹을 하나 이상 선택하세요.');
  await dialog.getByRole('button',{name:'공유할 그룹'}).click();
  await page.getByRole('menuitemcheckbox',{name:'디자인 그룹'}).click();
  await page.keyboard.press('Escape');
  await dialog.getByRole('button',{name:'확인',exact:true}).click();
  await expect(dialog).toContainText('공유 권한을 저장하지 못했습니다.');
  await expect(dialog.getByRole('list',{name:'선택한 공유 그룹'})).toContainText('디자인 그룹');
  await dialog.getByRole('button',{name:'확인',exact:true}).click();
  await expect(dialog).toBeHidden();
  await expect(page.getByTestId('saved-sharing')).toHaveText('특정 그룹: design');
  record.checks.push('group required validation, save failure retains selection, retry succeeds');
  await trigger.click();
  await page.getByRole('radio',{name:'나만 보기'}).click();
  await page.getByRole('dialog').getByRole('button',{name:'취소',exact:true}).click();
  await expect(page.getByTestId('saved-sharing')).toHaveText('특정 그룹: design');
  await trigger.click();
  await page.getByRole('radio',{name:'나만 보기'}).click();
  await page.getByRole('dialog').getByRole('button',{name:'확인',exact:true}).click();
  await expect(page.getByRole('dialog')).toBeHidden();
  await expect(page.getByTestId('saved-sharing')).toHaveText('나만 보기');
  record.checks.push('cancel discards draft; private saves and clears groups');
  await page.screenshot({path:`artifacts/${version}/desktop.png`,fullPage:true});
  await page.setViewportSize({width:390,height:844});
  await expect(save).toBeVisible(); await expect(search).toBeVisible();
  record.mobileOverflow=await page.evaluate(()=>({scrollWidth:document.documentElement.scrollWidth,innerWidth:innerWidth}));
  await page.screenshot({path:`artifacts/${version}/mobile.png`,fullPage:true});
  await page.goto(`http://127.0.0.1:${port}/mcp.html`);
  const mcpSave=page.getByRole('button',{name:'저장하기',exact:true});
  await mcpSave.click();
  await expect(mcpSave).toHaveAttribute('aria-busy','true');
  await mcpSave.evaluate(el=>{el.click();el.click();});
  await expect(page.locator('main')).toHaveAttribute('data-attempts','1');
  await expect(page.getByRole('status')).toContainText('저장하지 못했습니다');
  await mcpSave.click();
  await expect(page.getByRole('status')).toHaveText('저장 완료');
  await expect(page.locator('main')).toHaveAttribute('data-attempts','2');
  record.checks.push('unmodified SaveButton code downloaded from version-matched remote MCP executes successfully');
  await page.keyboard.press('Tab');
  record.focusedTag=await page.evaluate(()=>document.activeElement?.tagName);
  record.status='passed';
 } catch(e) {record.status='failed';record.error=String(e);await page.screenshot({path:`artifacts/${version}/browser-failure.png`,fullPage:true});}
 results.push(record);await page.close();
}
await fs.writeFile('artifacts/browser-results.json',JSON.stringify(results,null,2));
console.log(JSON.stringify(results,null,2));
await browser.close();
if(results.some(r=>r.status==='failed'||r.pageErrors.length)) process.exitCode=1;
